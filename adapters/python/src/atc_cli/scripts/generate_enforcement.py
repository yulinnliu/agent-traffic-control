#!/usr/bin/env python3
"""Generate each harness's native deny configuration from hard-deny.yaml.

Writes three files under --out, deterministically, so a consuming project can commit them and diff them in CI:

    claude-code/settings.json   permissions.deny for Claude Code
    codex/hard-deny.rules       prefix_rule block for ~/.codex/rules
    git-hooks/pre-commit        refuses a commit adding a hard-denied path (mode 0755)

--workspace adds the machine-local segment: an Edit deny on every registered project's state root, as
absolute paths, written to --local-out (never under --out). A filesystem glob holding a ${...} token is
refused (`unresolved-token`).

--hook-out writes the PreToolUse hook's table as the hook composes it (`compose_result`): the workspace
policy and every registered project's policy at `main`, and the workspace map. Command entries with a
hook-only condition reach the table only. This is `atc-maintain guard`.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import yaml

import globs
import policies

HEADER = "GENERATED by agent-traffic-control from hard-deny.yaml."
CODEX_BEGIN = "# BEGIN atc hard-deny"
CODEX_END = "# END atc hard-deny"
TOKEN = re.compile(r"\$\{([^}]*)\}")
# Claude Code checks path rules only for Read(path) and Edit(path); an Edit deny already covers Write and NotebookEdit.
CLAUDE_TOOLS = (("Read", {"read"}), ("Edit", {"edit", "write"}))
LOCAL_TOOLS = ("Edit",)
LOCAL_FILE = "claude-code/settings.local.json"
# Claude Code's absolute-path form; policy globs are repository-relative or ~-rooted, so never take it.
MACHINE_LOCAL = re.compile(r"^\w+\(//")
DRIVE = re.compile(r"^([A-Za-z]):/(.*)$")
# A command entry carrying one of these is enforced by the PreToolUse hook only; a prefix rule would deny more.
HOOK_ONLY = ("with_args", "unless_args", "push_targets", "background")
HOOK_TABLE = "pretooluse.json"
HOOK_TABLE_VERSION = 1
ENGINE = "pretooluse_hook.py"
# The distribution `uv tool install` names its tool environment after.
TOOL = "agent-traffic-control"
ENGINE_FILES = (ENGINE, "shell_words.py", "write_targets.py", "globs.py", "hook_state.py", "compose_child.py")
# The engine `atc hook` runs: the one beside this module, inside the installed `atc`.
HOOK_COMMAND = "atc hook"
# A hook entry ATC manages: `atc hook`, or an engine named by path, as a release copy's entry wrote it.
MANAGED_COMMAND = re.compile(r"(?:^|[\s\"'/\\])atc(?:\.exe)?[\"']?\s+hook\b")
ENGINE_DIR = Path(__file__).resolve().parent
# The hook scripts the engine replaces (the worktree cd guard and the write scope guard); install drops their
# entries. A pattern, so the test selector reads no edge to the cd guard's module.
RETIRED_GUARDS = re.compile(r"\b(?:worktree_cd|write_scope)_guard\.py\b")
CLAUDE_MATCHER = "Bash|PowerShell|Edit|Write|NotebookEdit"
CODEX_MATCHER = "Bash|apply_patch"
HOOK_TIMEOUT = 10
STATE_REASON = "Persistent project data is written only by the project's own tools."


def hook_only(command: dict) -> bool:
    return any(key in command for key in HOOK_ONLY)


def unresolved_tokens(hard: dict) -> list[str]:
    problems = []
    for index, (glob, _) in enumerate(policies.filesystem_rules(hard)):
        for name in TOKEN.findall(glob):
            problems.append(
                f'unresolved-token: filesystem.deny[{index}] "{glob}": Claude Code has no form for ${{{name}}}'
            )
    return problems


def claude_settings(hard: dict) -> str:
    deny: list[str] = []
    for command in hard.get("commands", {}).get("deny", []):
        if hook_only(command):
            continue
        prefix = " ".join(command["argv_prefix"])
        # A Bash deny alone turns off the PowerShell tool on Windows with Git Bash; a PowerShell rule keeps it on.
        deny += [f"Bash({prefix}:*)", f"PowerShell({prefix} *)"]
    for glob, modes in policies.filesystem_rules(hard):
        deny.extend(f"{tool}({glob})" for tool, covers in CLAUDE_TOOLS if covers & set(modes))
    return json.dumps({"permissions": {"deny": deny}}, indent=2) + "\n"


def codex_rules(hard: dict) -> str:
    lines = [
        f"# {HEADER} Do not edit.",
        "# Splice the block between the markers into ~/.codex/rules/default.rules;",
        "# regenerate and re-splice on a policy change. Only command prefixes map to",
        "# Codex rules; filesystem globs and capability ids are enforced elsewhere.",
        "#",
        CODEX_BEGIN,
    ]
    for command in hard.get("commands", {}).get("deny", []):
        if not hook_only(command):
            lines.append(f'prefix_rule(pattern={json.dumps(command["argv_prefix"])}, decision="forbidden")')
    lines.append(CODEX_END)
    return "\n".join(lines) + "\n"


def pre_commit_hook(hard: dict) -> str:
    basenames: list[str] = []
    prefixes: list[str] = []
    elsewhere: list[str] = []
    for glob, modes in policies.filesystem_rules(hard):
        label = glob if modes == policies.MODES else f"{glob}  [{', '.join(modes)}]"
        if not {"edit", "write"} & set(modes) or globs.is_tokenised(glob):
            elsewhere.append(label)
        elif glob.startswith("**/") and "/" not in glob[3:]:
            basenames.append(globs.basename_regex(glob[3:]))
        elif glob.endswith("/**") and "*" not in glob[:-3]:
            prefixes.append("^" + globs.basename_regex(glob[:-3]).replace("[^/]*", "") + "/")
        else:
            elsewhere.append(label)
    alternatives: list[str] = []
    if basenames:
        alternatives.append("(^|/)(" + "|".join(basenames) + ")$")
    alternatives.extend(prefixes)
    lines = [
        "#!/bin/sh",
        f"# {HEADER} Do not hand-edit;",
        "# regenerate on a policy change.",
        "#",
        "# Refuses a commit that adds or modifies a hard-denied path. Active when",
        "# core.hooksPath points at this directory.",
    ]
    if elsewhere:
        lines += ["#", "# Not git-enforced here (the runtime adapter's job):"]
        lines += [f"#   {label}" for label in elsewhere]
    lines.append("")
    if not alternatives:
        lines += ["# No repository-relative hard-denied paths; nothing to refuse.", "exit 0", ""]
        return "\n".join(lines)
    regex = "|".join(alternatives)
    lines += [
        f"hit=$(git diff --cached --name-only --diff-filter=AM | grep -E '{regex}' || true)",
        'if [ -n "$hit" ]; then',
        '    echo "pre-commit: refusing hard-denied path(s) (hard-deny.yaml):"',
        '    echo "$hit"',
        "    exit 1",
        "fi",
        "",
    ]
    return "\n".join(lines)


def _absolute(path: str) -> bool:
    return path.startswith("/") or DRIVE.match(path) is not None


def state_roots(workspace: Path) -> list[str]:
    """Each registered project's state root as an absolute POSIX path, in map order."""
    doc = yaml.safe_load(workspace.read_text(encoding="utf-8")) or {}
    base = doc.get("workspace_root") if isinstance(doc, dict) else None
    if not isinstance(base, str) or not _absolute(base.replace("\\", "/")):
        raise ValueError(f"{workspace}: workspace_root must be an absolute path")
    base = base.replace("\\", "/").rstrip("/")
    roots = []
    for entry in (doc.get("projects") or {}).values():
        state = entry.get("state") if isinstance(entry, dict) else None
        if not isinstance(state, str) or not state.strip():
            continue
        state = state.replace("\\", "/").rstrip("/")
        roots.append(state if _absolute(state) else f"{base}/{state}")
    return roots


def claude_absolute(path: str) -> str:
    """`C:/x` becomes `//c/x` and `/x` becomes `//x`: Claude Code matches Windows paths in POSIX form."""
    drive = DRIVE.match(path)
    return f"//{drive[1].lower()}/{drive[2]}" if drive else f"/{path}"


def local_settings(roots: list[str]) -> str:
    deny = [f"{tool}({claude_absolute(root)}/**)" for root in roots for tool in LOCAL_TOOLS]
    return json.dumps({"permissions": {"deny": deny}}, indent=2) + "\n"


def _norm(path: str | Path, base: Path) -> str:
    """The hook's form of a path: absolute, long, case-folded Windows form (shell_words.native)."""
    import shell_words
    import write_targets
    return write_targets.long_form(shell_words.native(str(path), str(base)))


ENV_REFERENCE = re.compile(r"%(\w+)%|\$\{(\w+)\}|\$(\w+)")
ROOT_LABEL = "policies/hard-deny.yaml"
SKEW_HINT = (" If atc doctor reports the installed atc older than main, installing the latest release may be "
             "the fix; otherwise fix the policy in a topic and integrate it, and if this main is not the reviewed "
             "one, the Owner resets it to its upstream.")


def _expand_root(entry: str, home: Path, environ: dict[str, str] | os._Environ) -> str:
    """An `agent_write_roots` entry with `%VAR%`, `${VAR}`, `$VAR` and a leading `~` expanded (an unknown variable
    stays as written)."""
    def value(match: re.Match) -> str:
        name = next(group for group in match.groups() if group)
        return environ.get(name, match.group(0))
    entry = ENV_REFERENCE.sub(value, entry)
    return str(home) + entry[1:] if entry.startswith("~") else entry


def env_names(doc: dict) -> list[str]:
    """The environment variables the map's `agent_write_roots` name, in order: inputs of the table's key."""
    names: list[str] = []
    for root in doc.get("agent_write_roots") or []:
        if isinstance(root, str):
            for match in ENV_REFERENCE.finditer(root):
                name = next(group for group in match.groups() if group)
                if name not in names:
                    names.append(name)
    return names


def _parse_map(data: bytes, workspace: Path) -> tuple[Path, dict]:
    import hook_state
    try:
        doc = policies.strict_load(data.decode("utf-8-sig")) or {}
    except (UnicodeDecodeError, yaml.YAMLError) as exc:
        raise hook_state.Failure("WORKSPACE_INVALID", f"{workspace}: {exc}; the Owner fixes it.") from None
    base = doc.get("workspace_root") if isinstance(doc, dict) else None
    if not isinstance(base, str) or not _absolute(base.replace("\\", "/")):
        raise hook_state.Failure("WORKSPACE_INVALID", f"{workspace}: workspace_root must be an absolute path; "
                                                      "the Owner fixes it.")
    for root in doc.get("agent_write_roots") or []:
        if not isinstance(root, str) or not root.strip():
            raise hook_state.Failure("WORKSPACE_INVALID", f"{workspace}: agent_write_roots holds a non-string or "
                                                          "empty entry; the Owner fixes it.")
    return Path(base), doc


def _sources(workspace: Path, base: Path, doc: dict) -> list[dict]:
    """Each policy source, the workspace policy first: a Git repository read at `main`, or (a workspace that is
    no governance checkout) the workspace's own `policies/`; with the scopes of its repository-relative globs."""
    import content
    import hook_state
    checkout = doc.get(content.GOVERNANCE_CHECKOUT)
    root_scopes = [(base, 0), (base / "worktrees" / "root", 1)]
    if isinstance(checkout, str) and checkout.strip():
        sources = [{"label": ROOT_LABEL, "kind": "git", "path": str((workspace.parent / checkout).resolve()),
                    "scopes": root_scopes}]
    elif content.holds_governance(workspace.parent):
        raise hook_state.Failure("GOVERNANCE_CHECKOUT_UNSET", f"{workspace.parent} is a checkout of the governance "
                                 f"repository but {workspace.name} has no governance_checkout; the Owner adds "
                                 "governance_checkout: . to it.")
    else:
        sources = [{"label": ROOT_LABEL, "kind": "file", "path": str(base / "policies"),
                    "files": [f"{kind}.yaml" for kind in policies.KINDS], "scopes": root_scopes}]
    for name, entry in (doc.get("projects") or {}).items():
        if not isinstance(entry, dict) or not isinstance(entry.get("repo"), str):
            continue
        repo = base / entry["repo"]
        scopes = [(repo, 0)]
        if isinstance(entry.get("worktrees"), str):
            scopes.append((base / entry["worktrees"], 1))
        sources.append({"label": f"projects.{name}", "kind": "git", "path": str(repo), "scopes": scopes})
    return sources


def _public(source: dict) -> dict:
    return {k: v for k, v in source.items() if k != "scopes"}


def _git_texts(source: dict, sha: str, home: Path) -> dict[str, str]:
    """The policy files of commit ``sha``, read from its Git objects by name; POLICY_TOO_LARGE above the limit."""
    import hook_state
    repo, where = Path(source["path"]), f"{source['label']} {source['path']}@{sha}"
    names = [f"{sha}:policies/{kind}.yaml" for kind in policies.KINDS]
    try:
        check = hook_state.git(repo, ["cat-file", "--batch-check"], home, data=("\n".join(names) + "\n").encode())
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise hook_state.Failure("MAIN_UNREADABLE", f"{where}: git cat-file failed ({exc}).") from None
    if check.returncode:
        raise hook_state.Failure("MAIN_UNREADABLE", f"{where}: git cat-file failed "
                                 f"({check.stderr.decode('utf-8', 'replace').strip()}).")
    wanted: list[tuple[str, str]] = []
    for kind, line in zip(policies.KINDS, check.stdout.decode("utf-8", "replace").splitlines()):
        parts = line.split()
        if len(parts) != 3 or parts[1] != "blob":
            continue
        if int(parts[2]) > hook_state.MAX_POLICY_BYTES:
            raise hook_state.Failure("POLICY_TOO_LARGE", f"{where}: policies/{kind}.yaml is {parts[2]} bytes, over "
                                     f"{hook_state.MAX_POLICY_BYTES}.{SKEW_HINT}")
        wanted.append((kind, parts[0]))
    if not wanted:
        return {}
    batch = hook_state.git(repo, ["cat-file", "--batch"], home,
                           data=("\n".join(oid for _, oid in wanted) + "\n").encode())
    out, position, texts = batch.stdout, 0, {}
    for kind, _ in wanted:
        end = out.index(b"\n", position)
        size = int(out[position:end].split()[2])
        texts[kind] = out[end + 1:end + 1 + size].decode("utf-8")
        position = end + 1 + size + 1
    return texts


def _file_texts(source: dict) -> dict[str, str]:
    import hook_state
    texts = {}
    for kind in policies.KINDS:
        path = Path(source["path"]) / f"{kind}.yaml"
        if not path.is_file():
            continue
        if path.stat().st_size > hook_state.MAX_POLICY_BYTES:
            raise hook_state.Failure("POLICY_TOO_LARGE", f"{source['label']} {path}: {path.stat().st_size} bytes, "
                                                         f"over {hook_state.MAX_POLICY_BYTES}.")
        texts[kind] = path.read_text(encoding="utf-8")
    return texts


def _atc_identity() -> dict:
    from importlib import metadata
    try:
        version = metadata.version(TOOL)
    except metadata.PackageNotFoundError:
        version = "unknown"
    try:
        import release_pin
        release = release_pin.installed()
    except Exception:  # identity is reporting only
        release = None
    return {"version": version, "commit": release.commit if release else None}


def compose_result(workspace: Path, home: Path, atc_home: Path, key_out: Path | None = None,
                   map_bytes: bytes | None = None, schemas: Path = policies.SCHEMAS) -> dict:
    """Compose the hook's table from the map and each source at the commit its key names: `{key, sources,
    env_names, inputs, table}`, or `{key, ..., failure}` (docs/ENFORCEMENT.md § PreToolUse hook, Table).
    ``map_bytes`` stands for the map's text (`atc add` checks a map before writing it)."""
    import hashlib
    import hook_state
    result: dict = {"atc": _atc_identity()}
    data = map_bytes
    try:
        if data is None:
            try:
                data = workspace.read_bytes()
            except OSError as exc:
                raise hook_state.Failure("WORKSPACE_MISSING", f"{workspace} cannot be read "
                                         f"({exc.strerror or exc}); the Owner restores it.") from None
        map_hash = hashlib.sha256(data).hexdigest()
        result.update(key=hook_state.make_key(workspace, map_hash, None, None, home), sources=None, env_names=None)
        base, doc = _parse_map(data, workspace)
        sources = _sources(workspace, base, doc)
        names = env_names(doc)
        public = [_public(source) for source in sources]
        key = hook_state.make_key(workspace, map_hash, public, names, home)
        result.update(key=key, sources=public, env_names=names)
        if key_out is not None:
            hook_state.write_json(key_out, {"key": key, "sources": public, "env_names": names})
        loaded, inputs = [], {}
        for source, (_, _, _, value) in zip(sources, key["sources"]):
            if source["kind"] == "git":
                if value is None:
                    raise hook_state.Failure("MAIN_UNREADABLE", f"{source['label']}: {source['path']} has no "
                                             "readable refs/heads/main; the Owner repairs the repository or runs "
                                             "atc remove.")
                where, texts = f"{source['label']} {source['path']}@{value}", _git_texts(source, value, home)
                inputs[source["label"]] = f"{source['path']}@{value}"
            else:
                where, texts = f"{source['label']} {source['path']}", _file_texts(source)
                inputs[source["label"]] = f"{source['path']} sha256 {value}"
            hard = None
            if "hard-deny" in texts:
                try:
                    hard = policies.load_texts(texts, schemas)["hard-deny"]
                except policies.PolicyError as exc:
                    raise hook_state.Failure("POLICY_INVALID", "; ".join(f"{where}: {p}" for p in exc.problems)
                                             + "." + SKEW_HINT) from None
                problems = unresolved_tokens(hard)
                if problems:
                    raise hook_state.Failure("POLICY_INVALID", "; ".join(f"{where}: {p}" for p in problems)
                                             + "." + SKEW_HINT)
            loaded.append((source, hard))
        result.update(inputs=inputs, table=_table(workspace, base, doc, loaded, home, atc_home))
    except hook_state.Failure as failure:
        result["failure"] = failure.as_dict()
    return result


def fresh_table(workspace: Path, home: Path, atc_home: Path, schemas: Path = policies.SCHEMAS) -> str:
    """The composed table as LF JSON text; raises hook_state.Failure."""
    import hook_state
    result = compose_result(workspace, home, atc_home, schemas=schemas)
    if "failure" in result:
        raise hook_state.Failure(result["failure"]["token"], result["failure"]["detail"])
    return json.dumps(result["table"], indent=2, ensure_ascii=False) + "\n"


def _table(workspace: Path, base: Path, doc: dict, loaded: list[tuple[dict, dict | None]], home: Path,
           atc_home: Path) -> dict:
    """The PreToolUse hook's table from the loaded policies and the map (docs/ENFORCEMENT.md § PreToolUse hook).

    It protects its state directory, the map, a workspace's own policies, the engine's files and the installed
    `atc`'s uv tool environment."""
    import hook_state
    commands: list[dict] = []
    filesystem: list[dict] = []
    seen: set[str] = set()
    for source, hard in loaded:
        if hard is None:
            continue
        label, scopes = source["label"], source["scopes"]
        for command in hard.get("commands", {}).get("deny", []):
            condition = {k: command[k] for k in ("argv_prefix", *HOOK_ONLY) if k in command}
            key = json.dumps(condition, sort_keys=True)
            if key not in seen:
                seen.add(key)
                commands.append({"id": command["id"], **condition, "reason": command.get("reason", ""),
                                 "source": label})
        entries = hard.get("filesystem", {}).get("deny", [])
        for index, (glob, modes) in enumerate(policies.filesystem_rules(hard)):
            entry = entries[index]
            reason = entry.get("reason", "") if isinstance(entry, dict) else ""
            if glob.startswith("~"):
                rule_glob, scope = _norm(str(home) + glob[1:], base).replace("\\", "/"), None
            else:
                rule_glob, scope = glob, [{"base": _norm(path, base), "depth": depth} for path, depth in scopes]
            key = json.dumps([rule_glob, modes, scope])
            if key not in seen:
                seen.add(key)
                filesystem.append({"id": f"filesystem.deny[{index}]", "glob": rule_glob, "modes": list(modes),
                                   "scope": scope, "reason": reason, "source": label})
    projects = {n: e for n, e in (doc.get("projects") or {}).items() if isinstance(e, dict)}
    for name, entry in projects.items():
        state = entry.get("state")
        if isinstance(state, str) and state.strip():
            filesystem.append({"id": f"state.{name}", "glob": _norm(base / state, base).replace("\\", "/") + "/**",
                               "modes": ["edit", "write"], "scope": None, "reason": STATE_REASON,
                               "source": "workspace.yaml"})
    worktrees = [_norm(base / "worktrees", base)]
    for entry in projects.values():
        if isinstance(entry.get("worktrees"), str):
            path = _norm(base / entry["worktrees"], base)
            if not any(path == root or path.startswith(root + "\\") for root in worktrees):
                worktrees.append(path)
    write_roots = [_norm(base, base)]
    for root in doc.get("agent_write_roots") or []:
        path = _norm(_expand_root(root, home, os.environ), base)
        if path not in write_roots:
            write_roots.append(path)
    tool = tool_environment()
    own = [_norm(Path(s["path"]), base) for s, _ in loaded if s["kind"] == "file"]
    protected = ([_norm(Path(atc_home) / hook_state.ENFORCEMENT, base), _norm(workspace, base), *own]
                 + [_norm(ENGINE_DIR / name, base) for name in ENGINE_FILES]
                 + ([_norm(tool, base)] if tool is not None else []))
    return {"version": HOOK_TABLE_VERSION, "commands": commands, "filesystem": filesystem,
            "worktrees": worktrees, "write_roots": write_roots, "protected": protected}


def tool_environment() -> Path | None:
    """The uv tool environment of the running `atc` (`sys.prefix` holding uv's `uv-receipt.toml`), which `uv tool
    install` replaces; None when it runs from elsewhere."""
    prefix = Path(sys.prefix)
    return prefix if (prefix / "uv-receipt.toml").is_file() else None


def default_home() -> Path:
    return Path.home()


def default_atc_home(home: Path) -> Path:
    return Path(home) / ".atc"


def engine_command(workspace: Path, harness: str, home: Path, atc_home: Path) -> str:
    """The hook command: `atc hook`, which runs the engine of whatever `atc` is installed, so a new install needs no
    new entry; it names the map and the home and ATC home the hook keeps its state under, by forward-slash path."""
    return (f'{HOOK_COMMAND} --harness {harness} --workspace "{Path(workspace).absolute().as_posix()}" '
            f'--home "{Path(home).absolute().as_posix()}" --atc-home "{Path(atc_home).absolute().as_posix()}"')


def hook_group(harness: str, command: str) -> dict:
    hook = {"type": "command", "command": command, "timeout": HOOK_TIMEOUT}
    if harness == "claude":
        hook["onFailure"] = "block"
    return {"matcher": CLAUDE_MATCHER if harness == "claude" else CODEX_MATCHER, "hooks": [hook]}


def _managed(hook: object) -> bool:
    if not isinstance(hook, dict):
        return False
    text = f"{hook.get('command', '')} {' '.join(map(str, hook.get('args') or []))}"
    return ENGINE in text or MANAGED_COMMAND.search(text) is not None or RETIRED_GUARDS.search(text) is not None


def _settings(path: Path) -> dict:
    text = _read(path)
    if text is None:
        return {}
    doc = json.loads(text.removeprefix("﻿"))
    if not isinstance(doc, dict):
        raise ValueError(f"{path}: top level is not a JSON object")
    return doc


def install_hook(path: Path, group: dict) -> None:
    """Replace every PreToolUse entry running the engine or a retired guard with `group`; keep the rest."""
    doc = _settings(path)
    hooks = doc.setdefault("hooks", {})
    kept = []
    for entry in hooks.get("PreToolUse") or []:
        items = [hook for hook in entry.get("hooks", []) if not _managed(hook)] if isinstance(entry, dict) else []
        if items:
            kept.append({**entry, "hooks": items})
    hooks["PreToolUse"] = [*kept, group]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def hooks_current(path: Path, group: dict) -> bool:
    """The file's PreToolUse entries that run the engine or a retired guard are exactly `group`."""
    return entry_state(path, group) == "current"


def entry_state(path: Path, group: dict) -> str:
    """`current` when the file's managed PreToolUse entries are exactly `group`, `missing` when it has none,
    else `outdated` (an unreadable file included)."""
    try:
        doc = _settings(path)
    except ValueError:
        return "outdated"
    entries = (doc.get("hooks") or {}).get("PreToolUse") or []
    managed = [e for e in entries if isinstance(e, dict) and any(_managed(h) for h in e.get("hooks", []))]
    if not managed:
        return "missing"
    return "current" if managed == [group] else "outdated"


def render(hard: dict) -> dict[str, str]:
    return {
        "claude-code/settings.json": claude_settings(hard),
        "codex/hard-deny.rules": codex_rules(hard),
        "git-hooks/pre-commit": pre_commit_hook(hard),
    }


def write_if_changed(path: Path, content: str) -> bool:
    """Write `content` as LF unless the file already holds it, ignoring EOL style; True when written."""
    if _read(path) == content:
        return False
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def _read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None


def _codex_block(text: str) -> list[str]:
    lines = text.split("\n")
    return lines[lines.index(CODEX_BEGIN):lines.index(CODEX_END) + 1]


def deny_entries(path: Path) -> list | None:
    """The deny list of a settings file, which an editor may have saved with a UTF-8 BOM."""
    text = _read(path)
    try:
        return json.loads(text.removeprefix("﻿"))["permissions"]["deny"] if text is not None else None
    except (ValueError, KeyError, TypeError):
        return None


def machine_local(deny: list | None, keep: bool) -> list | None:
    """The machine-local segment of a deny list (`keep=True`), or the rest of it."""
    if not isinstance(deny, list):
        return deny
    return [e for e in deny if (isinstance(e, str) and MACHINE_LOCAL.match(e) is not None) == keep]


def live_drift(
    files: dict[str, str],
    claude: Path | None,
    codex: Path | None,
    hook: Path | None,
    local: dict[str, str] | None = None,
    claude_local: Path | None = None,
) -> list[str]:
    """`local` is the machine-local render, None when no workspace map names a state root;
    with one, --live-claude compares only the policy segment of the file's deny list."""
    drift = []
    if claude is not None:
        current = deny_entries(claude)
        if local is not None:
            current = machine_local(current, keep=False)
        if current != json.loads(files["claude-code/settings.json"])["permissions"]["deny"]:
            drift.append(f"live-claude ({claude})")
    if claude_local is not None:
        expected = json.loads(local[LOCAL_FILE])["permissions"]["deny"] if local else []
        if machine_local(deny_entries(claude_local), keep=True) != expected:
            drift.append(f"live-claude-local ({claude_local})")
    if codex is not None:
        text = _read(codex)
        if text is None or text.split("\n").count(CODEX_BEGIN) != 1 or text.split("\n").count(CODEX_END) != 1:
            drift.append(f"live-codex ({codex}): no single atc hard-deny block")
        elif _codex_block(text) != _codex_block(files["codex/hard-deny.rules"]):
            drift.append(f"live-codex ({codex})")
    if hook is not None and _read(hook) != files["git-hooks/pre-commit"]:
        drift.append(f"live-hook ({hook})")
    return drift


def drift(files: dict[str, str], out: Path) -> list[str]:
    return [rel for rel, content in files.items() if _read(out / rel) != content]




def main(argv: list[str] | None = None) -> int:
    import cli_conventions
    parser = argparse.ArgumentParser(prog="atc-maintain guard", allow_abbrev=False, **cli_conventions.form(
        __doc__.splitlines()[0], "\n".join(__doc__.strip().splitlines()[2:]),
        exit="0 generated, or current under --check; 1 drift under --check, or a policy problem; 2 usage error",
        see="docs/ENFORCEMENT.md § Outputs, § Drift, § PreToolUse hook"))
    parser.add_argument("--policies", type=Path, metavar="DIR",
                        help="the policy directory holding hard-deny.yaml (required with --out)")
    parser.add_argument("--out", type=Path, metavar="DIR",
                        help="where the generated files go (committed by the consuming project)")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 when --out or a --live-* copy differs from the generated output")
    parser.add_argument("--live-claude", type=Path, metavar="FILE",
                        help="with --check: a Claude settings file whose permissions.deny must match")
    parser.add_argument("--live-claude-local", type=Path, metavar="FILE",
                        help="with --check: a Claude settings file whose absolute-path deny entries must match the "
                             "machine-local segment")
    parser.add_argument("--live-codex", type=Path, metavar="FILE",
                        help="with --check: a Codex rules file whose atc hard-deny block must match")
    parser.add_argument("--live-hook", type=Path, metavar="FILE",
                        help="with --check: an installed pre-commit hook that must match")
    parser.add_argument("--workspace", type=Path, metavar="FILE",
                        help="workspace.yaml whose project state roots form the machine-local segment "
                             "(atc passes the root's own when present)")
    parser.add_argument("--local-out", type=Path, metavar="DIR",
                        help=f"with --workspace: directory for the machine-local {LOCAL_FILE}")
    parser.add_argument("--hook-out", type=Path, metavar="DIR",
                        help=f"with --workspace: write the PreToolUse hook's {HOOK_TABLE} to DIR")
    parser.add_argument("--live-hook-table", type=Path, metavar="FILE",
                        help="with --check and --workspace: an installed hook table that must match")
    parser.add_argument("--live-claude-hooks", type=Path, metavar="FILE",
                        help="with --check and --workspace: a Claude settings file whose hook entry must match")
    parser.add_argument("--live-codex-hooks", type=Path, metavar="FILE",
                        help="with --check and --workspace: a Codex hooks.json whose hook entry must match")
    parser.add_argument("--schemas", type=Path, default=policies.SCHEMAS, metavar="DIR",
                        help="policy schema directory (default: the copy packaged with atc)")
    cli_conventions.add_json(parser)
    args = parser.parse_args(argv)
    native_live = args.live_claude or args.live_claude_local or args.live_codex or args.live_hook
    live_hooks = args.live_hook_table or args.live_claude_hooks or args.live_codex_hooks
    hook_write = args.hook_out is not None
    if (args.policies is None) != (args.out is None):
        parser.error("--policies and --out go together")
    if not args.check and (native_live or live_hooks):
        parser.error("the --live-* options require --check")
    if args.policies is None and not hook_write and not (args.check and live_hooks):
        parser.error("--policies and --out are required unless --hook-out or a --live-*-hooks check is given")
    if args.policies is None and native_live:
        parser.error("--live-claude, --live-claude-local, --live-codex and --live-hook require --policies and --out")
    if args.check and hook_write:
        parser.error("--hook-out writes; with --check use --live-hook-table")
    if (hook_write or live_hooks) and not args.workspace:
        parser.error("--hook-out and the --live-*-hooks checks require --workspace")
    if args.local_out and not args.workspace:
        parser.error("--local-out requires --workspace")
    if args.local_out and args.out and args.local_out.resolve().is_relative_to(args.out.resolve()):
        parser.error("--local-out must lie outside --out, which is committed and holds no absolute path")

    def done(verdict: str, lines: list[str], code: int, stop: tuple[str, str, str] | None = None,
             **fields) -> int:
        """``lines`` is the verdict line and its indented details; ``stop`` the refusal's token, detail and hint."""
        if args.json:
            print(json.dumps({"verdict": verdict, **fields}, indent=2))
            return code
        print("\n".join(lines))
        if stop:
            print(f"STOP {stop[0]}: {stop[1]}", file=sys.stderr)
            print(f"hint: {stop[2]}", file=sys.stderr)
        return code

    def problem(problems: list[str]) -> int:
        return done("PROBLEMS", [f"PROBLEMS {len(problems)} found", *(f"  {p}" for p in problems)], 1,
                    ("POLICY_INVALID", "each problem line names the policy file and the rule",
                     "fix them, then run atc-maintain guard again"), problems=problems)

    files: dict[str, str] = {}
    if args.policies is not None:
        try:
            loaded = policies.load(args.policies, args.schemas)
        except policies.PolicyError as exc:
            return problem(list(exc.problems))
        if "hard-deny" not in loaded:
            return problem([f"missing hard-deny.yaml in {args.policies}"])
        problems = unresolved_tokens(loaded["hard-deny"])
        if problems:
            return problem(problems)
        files = render(loaded["hard-deny"])
    local = None
    if args.workspace and args.policies is not None:
        try:
            roots = state_roots(args.workspace)
        except (OSError, ValueError, yaml.YAMLError) as exc:
            return problem([f"workspace: {exc}"])
        local = {LOCAL_FILE: local_settings(roots)} if roots else None
    table = None
    groups: dict[str, dict] = {}
    home = default_home()
    if hook_write or live_hooks:
        import hook_state
        try:
            table = fresh_table(args.workspace.absolute(), home, default_atc_home(home), args.schemas)
        except hook_state.Failure as exc:
            return problem([f"{exc.token}: {exc.detail}"])
        groups = {h: hook_group(h, engine_command(args.workspace, h, home, default_atc_home(home)))
                  for h in ("claude", "codex")}
    if args.check:
        found = []
        if args.policies is not None:
            found += drift(files, args.out) + live_drift(
                files, args.live_claude, args.live_codex, args.live_hook, local, args.live_claude_local
            )
            if local and args.local_out:
                found += [f"machine-local {rel}" for rel in drift(local, args.local_out)]
        if args.live_hook_table and _read(args.live_hook_table) != table:
            found.append(f"live-hook-table ({args.live_hook_table})")
        if args.live_claude_hooks and not hooks_current(args.live_claude_hooks, groups["claude"]):
            found.append(f"live-claude-hooks ({args.live_claude_hooks})")
        if args.live_codex_hooks and not hooks_current(args.live_codex_hooks, groups["codex"]):
            found.append(f"live-codex-hooks ({args.live_codex_hooks})")
        if found:
            return done("DRIFT", ["DRIFT " + ", ".join(found)], 1,
                        ("DRIFT", "the enforcement configs differ from the policies",
                         "regenerate with atc-maintain guard --policies DIR --out DIR; the Owner runs "
                         "atc guard --install for the hook entries"), drift=found)
        return done("CURRENT", ["CURRENT enforcement configs"], 0, drift=[])
    lines = []
    if args.policies is not None:
        for rel, content in files.items():
            target = args.out / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            write_if_changed(target, content)
        os.chmod(args.out / "git-hooks/pre-commit", 0o755)
        lines.append("  files: " + ", ".join(files))
    local_target = None
    if local and args.local_out:
        local_target = args.local_out / LOCAL_FILE
        local_target.parent.mkdir(parents=True, exist_ok=True)
        write_if_changed(local_target, local[LOCAL_FILE])
        lines.append(f"  machine-local: {local_target} (from {args.workspace})")
    elif local:
        lines.append(f"  machine-local: {args.workspace} names state roots; pass --local-out DIR to write {LOCAL_FILE}")
    table_target = None
    installed: list[str] = []
    if table is not None:
        table_target = args.hook_out / HOOK_TABLE
        table_target.parent.mkdir(parents=True, exist_ok=True)
        write_if_changed(table_target, table)
        lines.append(f"  hook-table: {table_target}")
    return done("GENERATED", ["GENERATED enforcement configs", *lines], 0, files=list(files),
                local=str(local_target) if local_target else None, hook_table=str(table_target) if table_target else None, installed=installed)


if __name__ == "__main__":
    sys.exit(main())
