#!/usr/bin/env python3
"""Generate each harness's native deny configuration from hard-deny.yaml.

    generate_enforcement.py --policies <dir> --out <dir>
        [--workspace FILE [--local-out <dir>]]
        [--check [--live-claude PATH] [--live-claude-local PATH] [--live-codex PATH] [--live-hook PATH]]

Writes three files under --out, deterministically, so a consuming project can
commit them and diff them in CI:

    claude-code/settings.json   permissions.deny for Claude Code
    codex/hard-deny.rules       prefix_rule block for ~/.codex/rules
    git-hooks/pre-commit        refuses a commit adding a hard-denied path (mode 0755)

--check regenerates in memory and exits 1 if any file under --out differs;
the --live-* options also compare the installed copies: the deny list of a
Claude settings file, the marker block of a Codex rules file, a whole hook.
A filesystem glob holding a ${...} token is refused (`unresolved-token`):
no harness output can resolve it.

--workspace adds the machine-local segment: an Edit deny on every
registered project's state root, as absolute paths, written to --local-out (never under --out) and compared through
--live-claude-local. The mapping is specified in docs/ENFORCEMENT.md.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

import yaml

import globs
import policies

HEADER = "GENERATED by agent-traffic-control from hard-deny.yaml."
CODEX_BEGIN = "# BEGIN atc hard-deny"
CODEX_END = "# END atc hard-deny"
TOKEN = re.compile(r"\$\{([^}]*)\}")
# Claude Code checks path rules only for Read(path) and Edit(path); an Edit deny already covers Write and NotebookEdit.
CLAUDE_TOOLS = (("Read", {"read"}), ("Edit", {"edit", "write"}))
LOCAL_TOOLS = ("Edit",)
LOCAL_FILE = "claude-code/settings.local.json"
# Claude Code's absolute-path form; policy globs are repository-relative or ~-rooted, so never take it.
MACHINE_LOCAL = re.compile(r"^\w+\(//")
DRIVE = re.compile(r"^([A-Za-z]):/(.*)$")


def unresolved_tokens(hard: dict) -> list[str]:
    problems = []
    for index, (glob, _) in enumerate(policies.filesystem_rules(hard)):
        for name in TOKEN.findall(glob):
            problems.append(
                f'unresolved-token: filesystem.deny[{index}] "{glob}": Claude Code has no form for ${{{name}}}'
            )
    return problems


def claude_settings(hard: dict) -> str:
    deny: list[str] = []
    for command in hard.get("commands", {}).get("deny", []):
        deny.append(f"Bash({' '.join(command['argv_prefix'])}:*)")
    for glob, modes in policies.filesystem_rules(hard):
        deny.extend(f"{tool}({glob})" for tool, covers in CLAUDE_TOOLS if covers & set(modes))
    return json.dumps({"permissions": {"deny": deny}}, indent=2) + "\n"


def codex_rules(hard: dict) -> str:
    lines = [
        f"# {HEADER} Do not edit.",
        "# Splice the block between the markers into ~/.codex/rules/default.rules;",
        "# regenerate and re-splice on a policy change. Only command prefixes map to",
        "# Codex rules; filesystem globs and capability ids are enforced elsewhere.",
        "#",
        CODEX_BEGIN,
    ]
    for command in hard.get("commands", {}).get("deny", []):
        lines.append(f'prefix_rule(pattern={json.dumps(command["argv_prefix"])}, decision="forbidden")')
    lines.append(CODEX_END)
    return "\n".join(lines) + "\n"


def pre_commit_hook(hard: dict) -> str:
    basenames: list[str] = []
    prefixes: list[str] = []
    elsewhere: list[str] = []
    for glob, modes in policies.filesystem_rules(hard):
        label = glob if modes == policies.MODES else f"{glob}  [{', '.join(modes)}]"
        if not {"edit", "write"} & set(modes) or globs.is_tokenised(glob):
            elsewhere.append(label)
        elif glob.startswith("**/") and "/" not in glob[3:]:
            basenames.append(globs.basename_regex(glob[3:]))
        elif glob.endswith("/**") and "*" not in glob[:-3]:
            prefixes.append("^" + globs.basename_regex(glob[:-3]).replace("[^/]*", "") + "/")
        else:
            elsewhere.append(label)
    alternatives: list[str] = []
    if basenames:
        alternatives.append("(^|/)(" + "|".join(basenames) + ")$")
    alternatives.extend(prefixes)
    lines = [
        "#!/bin/sh",
        f"# {HEADER} Do not hand-edit;",
        "# regenerate on a policy change.",
        "#",
        "# Refuses a commit that adds or modifies a hard-denied path. Active when",
        "# core.hooksPath points at this directory.",
    ]
    if elsewhere:
        lines += ["#", "# Not git-enforced here (the runtime adapter's job):"]
        lines += [f"#   {label}" for label in elsewhere]
    lines.append("")
    if not alternatives:
        lines += ["# No repository-relative hard-denied paths; nothing to refuse.", "exit 0", ""]
        return "\n".join(lines)
    regex = "|".join(alternatives)
    lines += [
        f"hit=$(git diff --cached --name-only --diff-filter=AM | grep -E '{regex}' || true)",
        'if [ -n "$hit" ]; then',
        '    echo "pre-commit: refusing hard-denied path(s) (hard-deny.yaml):"',
        '    echo "$hit"',
        "    exit 1",
        "fi",
        "",
    ]
    return "\n".join(lines)


def _absolute(path: str) -> bool:
    return path.startswith("/") or DRIVE.match(path) is not None


def state_roots(workspace: Path) -> list[str]:
    """Each registered project's state root as an absolute POSIX path, in map order."""
    doc = yaml.safe_load(workspace.read_text(encoding="utf-8")) or {}
    base = doc.get("workspace_root") if isinstance(doc, dict) else None
    if not isinstance(base, str) or not _absolute(base.replace("\\", "/")):
        raise ValueError(f"{workspace}: workspace_root must be an absolute path")
    base = base.replace("\\", "/").rstrip("/")
    roots = []
    for entry in (doc.get("projects") or {}).values():
        state = entry.get("state") if isinstance(entry, dict) else None
        if not isinstance(state, str) or not state.strip():
            continue
        state = state.replace("\\", "/").rstrip("/")
        roots.append(state if _absolute(state) else f"{base}/{state}")
    return roots


def claude_absolute(path: str) -> str:
    """`C:/x` becomes `//c/x` and `/x` becomes `//x`: Claude Code matches Windows paths in POSIX form."""
    drive = DRIVE.match(path)
    return f"//{drive[1].lower()}/{drive[2]}" if drive else f"/{path}"


def local_settings(roots: list[str]) -> str:
    deny = [f"{tool}({claude_absolute(root)}/**)" for root in roots for tool in LOCAL_TOOLS]
    return json.dumps({"permissions": {"deny": deny}}, indent=2) + "\n"


def render(hard: dict) -> dict[str, str]:
    return {
        "claude-code/settings.json": claude_settings(hard),
        "codex/hard-deny.rules": codex_rules(hard),
        "git-hooks/pre-commit": pre_commit_hook(hard),
    }


def write_if_changed(path: Path, content: str) -> bool:
    """Write `content` as LF unless the file already holds it, ignoring EOL style; True when written."""
    if _read(path) == content:
        return False
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def _read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None


def _codex_block(text: str) -> list[str]:
    lines = text.split("\n")
    return lines[lines.index(CODEX_BEGIN):lines.index(CODEX_END) + 1]


def deny_entries(path: Path) -> list | None:
    text = _read(path)
    try:
        return json.loads(text)["permissions"]["deny"] if text is not None else None
    except (ValueError, KeyError, TypeError):
        return None


def machine_local(deny: list | None, keep: bool) -> list | None:
    """The machine-local segment of a deny list (`keep=True`), or the rest of it."""
    if not isinstance(deny, list):
        return deny
    return [e for e in deny if (isinstance(e, str) and MACHINE_LOCAL.match(e) is not None) == keep]


def live_drift(
    files: dict[str, str],
    claude: Path | None,
    codex: Path | None,
    hook: Path | None,
    local: dict[str, str] | None = None,
    claude_local: Path | None = None,
) -> list[str]:
    """`local` is the machine-local render, None when no workspace map names a state root;
    with one, --live-claude compares only the policy segment of the file's deny list."""
    drift = []
    if claude is not None:
        current = deny_entries(claude)
        if local is not None:
            current = machine_local(current, keep=False)
        if current != json.loads(files["claude-code/settings.json"])["permissions"]["deny"]:
            drift.append(f"live-claude ({claude})")
    if claude_local is not None:
        expected = json.loads(local[LOCAL_FILE])["permissions"]["deny"] if local else []
        if machine_local(deny_entries(claude_local), keep=True) != expected:
            drift.append(f"live-claude-local ({claude_local})")
    if codex is not None:
        text = _read(codex)
        if text is None or text.split("\n").count(CODEX_BEGIN) != 1 or text.split("\n").count(CODEX_END) != 1:
            drift.append(f"live-codex ({codex}): no single atc hard-deny block")
        elif _codex_block(text) != _codex_block(files["codex/hard-deny.rules"]):
            drift.append(f"live-codex ({codex})")
    if hook is not None and _read(hook) != files["git-hooks/pre-commit"]:
        drift.append(f"live-hook ({hook})")
    return drift


def drift(files: dict[str, str], out: Path) -> list[str]:
    return [rel for rel, content in files.items() if _read(out / rel) != content]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--policies", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="exit 1 if --out differs from the generated output")
    parser.add_argument("--live-claude", type=Path, help="with --check: a Claude settings file whose permissions.deny must match")
    parser.add_argument("--live-claude-local", type=Path, help="with --check: a Claude settings file whose absolute-path deny entries must match the machine-local segment")
    parser.add_argument("--live-codex", type=Path, help="with --check: a Codex rules file whose atc hard-deny block must match")
    parser.add_argument("--live-hook", type=Path, help="with --check: an installed pre-commit hook that must match")
    parser.add_argument("--workspace", type=Path, help="workspace.yaml whose project state roots form the machine-local segment")
    parser.add_argument("--local-out", type=Path, help=f"with --workspace: directory for the machine-local {LOCAL_FILE}")
    parser.add_argument("--schemas", type=Path, default=policies.SCHEMAS)
    args = parser.parse_args(argv)
    if not args.check and (args.live_claude or args.live_claude_local or args.live_codex or args.live_hook):
        parser.error("--live-claude, --live-claude-local, --live-codex and --live-hook require --check")
    if args.local_out and not args.workspace:
        parser.error("--local-out requires --workspace")
    if args.local_out and args.local_out.resolve().is_relative_to(args.out.resolve()):
        parser.error("--local-out must lie outside --out, which is committed and holds no absolute path")
    try:
        loaded = policies.load(args.policies, args.schemas)
    except policies.PolicyError as exc:
        for problem in exc.problems:
            print(problem)
        return 1
    if "hard-deny" not in loaded:
        print(f"missing hard-deny.yaml in {args.policies}")
        return 1
    problems = unresolved_tokens(loaded["hard-deny"])
    if problems:
        for problem in problems:
            print(problem)
        return 1
    files = render(loaded["hard-deny"])
    local = None
    if args.workspace:
        try:
            roots = state_roots(args.workspace)
        except (OSError, ValueError, yaml.YAMLError) as exc:
            print(f"workspace: {exc}")
            return 1
        local = {LOCAL_FILE: local_settings(roots)} if roots else None
    if args.check:
        found = drift(files, args.out) + live_drift(
            files, args.live_claude, args.live_codex, args.live_hook, local, args.live_claude_local
        )
        if local and args.local_out:
            found += [f"machine-local {rel}" for rel in drift(local, args.local_out)]
        if found:
            print("drift: " + ", ".join(found))
            return 1
        print("ok: enforcement configs are current")
        return 0
    for rel, content in files.items():
        target = args.out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        write_if_changed(target, content)
    os.chmod(args.out / "git-hooks/pre-commit", 0o755)
    print("generated: " + ", ".join(files))
    if local and args.local_out:
        target = args.local_out / LOCAL_FILE
        target.parent.mkdir(parents=True, exist_ok=True)
        write_if_changed(target, local[LOCAL_FILE])
        print(f"machine-local: {target} (from {args.workspace})")
    elif local:
        print(f"machine-local: {args.workspace} names state roots; pass --local-out DIR to write {LOCAL_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
